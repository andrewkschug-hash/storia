/**
 * Package approved A1 sentence audio from the TTS gateway into the mobile bundle.
 *
 * Usage:
 *   node mobile/scripts/package-a1-audio.js
 *
 * Writes:
 *   mobile/content/audio/catalog.json
 *   mobile/public/audio/a1/*.mp3          ← web-playable URLs (/audio/a1/…)
 *   mobile/content/audio/bundled/*.mp3    ← validation mirror
 *   mobile/src/audio/media/*.mp3          ← native Metro assets
 *   mobile/src/audio/bundledAssets.ts
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', '..');
const mobileRoot = path.join(__dirname, '..');
const registryPath = path.join(root, 'services', 'tts-gateway', 'data', 'registry.json');
const audioSrcDir = path.join(root, 'services', 'tts-gateway', 'data', 'audio');
const publicDir = path.join(mobileRoot, 'public', 'audio', 'a1');
const mediaDir = path.join(mobileRoot, 'src', 'audio', 'media');
const bundledDir = path.join(mobileRoot, 'content', 'audio', 'bundled');
const catalogPath = path.join(mobileRoot, 'content', 'audio', 'catalog.json');

const MAX_CHAPTER = 20;

function chapterNumberFromContentId(contentId) {
  const match = String(contentId ?? '').match(/sentence:luca-a-roma-(\d{2}):/);
  if (!match) return null;
  return Number(match[1]);
}

function isA1SentenceAsset(asset) {
  const n = chapterNumberFromContentId(asset.contentId);
  return n != null && n >= 1 && n <= MAX_CHAPTER;
}

function main() {
  if (!fs.existsSync(registryPath)) {
    console.error('Missing registry:', registryPath);
    process.exit(1);
  }
  const registry = JSON.parse(fs.readFileSync(registryPath, 'utf8'));
  const assets = (registry.assets ?? []).filter(
    (a) =>
      (a.status === 'approved' || a.status === 'review_required') &&
      a.speed === 'normal' &&
      isA1SentenceAsset(a),
  );

  for (const dir of [publicDir, mediaDir, bundledDir]) fs.mkdirSync(dir, { recursive: true });

  const packaged = [];
  let missingSource = 0;

  for (const asset of assets) {
    const srcFile = path.join(audioSrcDir, `${asset.cacheKey ?? asset.id}.mp3`);
    if (!fs.existsSync(srcFile)) {
      missingSource += 1;
      continue;
    }
    const destName = `${asset.cacheKey ?? asset.id}.mp3`;
    fs.copyFileSync(srcFile, path.join(publicDir, destName));
    fs.copyFileSync(srcFile, path.join(mediaDir, destName));
    fs.copyFileSync(srcFile, path.join(bundledDir, destName));
    packaged.push({
      ...asset,
      status: 'approved',
      // Web: served from /public. Native: remapped via bundledAssets.
      audioUrl: `/audio/a1/${destName}`,
    });
  }

  const byContent = new Map();
  for (const asset of packaged) byContent.set(asset.contentId, asset);
  const unique = [...byContent.values()];

  fs.writeFileSync(catalogPath, JSON.stringify({ assets: unique }, null, 2) + '\n', 'utf8');

  const manifestPath = path.join(mobileRoot, 'src', 'audio', 'bundledAssets.ts');
  const lines = unique.map((asset) => {
    const file = path.basename(asset.audioUrl);
    const key = file.replace(/\.mp3$/i, '');
    return `  '${key}': require('./media/${file}'),`;
  });
  const manifest = `/* Auto-generated by scripts/package-a1-audio.js — do not edit. */
/* eslint-disable @typescript-eslint/no-require-imports */
export const bundledAudioModules: Record<string, number> = {
${lines.join('\n')}
};

export function bundledModuleForUrl(audioUrl: string): number | null {
  const file = audioUrl
    .replace(/^\\/audio\\/a1\\//, '')
    .replace(/^\\.\\/bundled\\//, '')
    .replace(/^bundled:/, '');
  const key = file.replace(/\\.mp3$/i, '');
  return bundledAudioModules[key] ?? null;
}
`;
  fs.writeFileSync(manifestPath, manifest, 'utf8');

  console.log(`Packaged ${unique.length} A1 audio assets → ${catalogPath}`);
  console.log(`Web public → ${publicDir}`);
  console.log(`Native media → ${mediaDir}`);
  console.log(`Validation mirror → ${bundledDir}`);
  if (missingSource > 0) console.warn(`Warning: ${missingSource} missing source MP3s`);
}

main();
