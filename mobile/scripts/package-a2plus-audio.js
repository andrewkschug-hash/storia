/**
 * MERGE A2+ genre paths sentence audio into the existing catalog.
 *
 * GUARANTEE:
 *   - NEVER modifies or overwrites frozen A1 (Ch 1–24) assets.
 *   - NEVER modifies or overwrites frozen Luca A2 (Ch 25–40) assets.
 *   - Strictly idempotent: safe to run multiple times.
 *
 * Usage:
 *   node mobile/scripts/package-a2plus-audio.js --dry-run
 *   node mobile/scripts/package-a2plus-audio.js
 */
const fs = require('fs');
const path = require('path');

const {
  A2_PLUS_STORIES,
  mobileRoot,
  repoRoot,
  contentRoot,
  ttsGatewayDir,
  loadJson,
  collectA2PlusClipPlan,
} = require('./a2plus-audio-common');

const registryPath = path.join(ttsGatewayDir, 'data', 'registry.json');
const audioSrcDir = path.join(ttsGatewayDir, 'data', 'audio');
const publicDir = path.join(mobileRoot, 'public', 'audio', 'a1');
const mediaDir = path.join(mobileRoot, 'src', 'audio', 'media');
const bundledDir = path.join(contentRoot, 'audio', 'bundled');
const catalogPath = path.join(contentRoot, 'audio', 'catalog.json');

function isProtectedLucaContentId(contentId) {
  return String(contentId ?? '').startsWith('sentence:luca-a-roma-');
}

function isA2PlusContentId(contentId) {
  const str = String(contentId ?? '');
  for (const storyId of Object.keys(A2_PLUS_STORIES)) {
    if (str.startsWith(`sentence:${storyId}-`)) return true;
  }
  return false;
}

function writeBundledAssets(assets) {
  const manifestPath = path.join(mobileRoot, 'src', 'audio', 'bundledAssets.ts');
  const byFile = new Map();
  for (const asset of assets) {
    const file = path.basename(asset.audioUrl || '');
    if (!file) continue;
    const key = file.replace(/\.mp3$/i, '');
    if (!fs.existsSync(path.join(mediaDir, file))) continue;
    if (!byFile.has(key)) byFile.set(key, file);
  }
  const lines = [...byFile.entries()].map(
    ([key, file]) => `  '${key}': require('./media/${file}'),`,
  );
  const manifest = `/* Auto-generated by scripts/package-a2plus-audio.js (merge A1 + Luca A2 + A2+ Genre Paths) — do not edit. */
/* Native/default: Metro asset requires. Web: see bundledAssets.web.ts (public /audio/a1). */
/* eslint-disable @typescript-eslint/no-require-imports */
export const bundledAudioModules: Record<string, number> = {
${lines.join('\n')}
};

export function bundledModuleForUrl(audioUrl: string): number | null {
  const file = audioUrl
    .replace(/^\\/audio\\/a1\\//, '')
    .replace(/^\\/audio\\/a2\\//, '')
    .replace(/^\\.\\/bundled\\//, '')
    .replace(/^bundled:/, '');
  const key = file.replace(/\\.mp3$/i, '');
  return bundledAudioModules[key] ?? null;
}
`;
  fs.writeFileSync(manifestPath, manifest, 'utf8');
}

function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run') || args.includes('--preflight');

  console.log('================================================================');
  console.log(`  A2+ AUDIO PACKAGING & MERGE — ${dryRun ? 'DRY-RUN' : 'WRITE'}`);
  console.log('================================================================\n');

  if (!fs.existsSync(catalogPath)) {
    console.error('FAIL-CLOSED: Missing existing catalog at', catalogPath);
    process.exit(1);
  }

  const existingCatalog = loadJson(catalogPath);
  const existingAssets = existingCatalog.assets ?? [];

  const protectedLucaBefore = existingAssets.filter((a) => isProtectedLucaContentId(a.contentId));
  const a1Before = protectedLucaBefore.filter((a) => {
    const m = a.contentId.match(/sentence:luca-a-roma-(\d{2}):/);
    const n = m ? Number(m[1]) : 0;
    return n >= 1 && n <= 24;
  });
  const lucaA2Before = protectedLucaBefore.filter((a) => {
    const m = a.contentId.match(/sentence:luca-a-roma-(\d{2}):/);
    const n = m ? Number(m[1]) : 0;
    return n >= 25 && n <= 40;
  });
  const a2plusBefore = existingAssets.filter((a) => isA2PlusContentId(a.contentId));

  console.log('PROTECTED ASSET AUDIT (BEFORE):');
  console.log(`  Frozen A1 Assets (Ch 1–24):        ${a1Before.length}`);
  console.log(`  Frozen Luca A2 Assets (Ch 25–40):  ${lucaA2Before.length}`);
  console.log(`  Total Protected Luca Assets:       ${protectedLucaBefore.length}`);
  console.log(`  Existing A2+ Genre Assets:         ${a2plusBefore.length}\n`);

  if (!fs.existsSync(registryPath)) {
    console.log(`No TTS registry found at ${registryPath}. Nothing to merge.`);
    process.exit(0);
  }

  const authoredPlan = collectA2PlusClipPlan();
  const authoredIds = new Set(authoredPlan.clips.map((c) => c.contentId));

  const registry = loadJson(registryPath);
  const incoming = (registry.assets ?? []).filter((a) => {
    if (!(a.status === 'approved' || a.status === 'review_required')) return false;
    if (a.speed !== 'normal') return false;
    if (!isA2PlusContentId(a.contentId)) return false;
    if (!authoredIds.has(a.contentId)) return false;
    return true;
  });

  const toAdd = [];
  const missingSourceFiles = [];
  const collisions = [];

  const protectedContentIds = new Set(protectedLucaBefore.map((a) => a.contentId));

  for (const asset of incoming) {
    if (protectedContentIds.has(asset.contentId)) {
      collisions.push(`Collision with protected Luca contentId: ${asset.contentId}`);
      continue;
    }

    const key = asset.cacheKey || asset.id;
    const destName = `${key}.mp3`;
    const srcFile = path.join(audioSrcDir, destName);

    if (!fs.existsSync(srcFile) || fs.statSync(srcFile).size === 0) {
      missingSourceFiles.push(asset.contentId);
      continue;
    }

    toAdd.push({
      ...asset,
      status: 'approved',
      audioUrl: `/audio/a1/${destName}`,
    });
  }

  if (collisions.length > 0) {
    console.error('FAIL-CLOSED: Collisions detected with protected assets. Aborting.');
    for (const c of collisions) console.error(`  - ${c}`);
    process.exit(1);
  }

  // Merge map keyed by contentId
  const mergedMap = new Map();
  for (const asset of existingAssets) mergedMap.set(asset.contentId, asset);
  for (const asset of toAdd) mergedMap.set(asset.contentId, asset);

  const merged = [...mergedMap.values()];
  const protectedLucaAfter = merged.filter((a) => isProtectedLucaContentId(a.contentId));
  const a2plusAfter = merged.filter((a) => isA2PlusContentId(a.contentId));

  console.log('MERGE PROJECTION:');
  console.log(`  Incoming Valid A2+ Assets:         ${toAdd.length}`);
  console.log(`  Missing MP3 Source Files:          ${missingSourceFiles.length}`);
  console.log(`  Total Catalog Size (Projected):    ${merged.length}`);
  console.log(`  Protected Luca Assets Preserved:   ${protectedLucaAfter.length} / ${protectedLucaBefore.length}`);
  console.log(`  A2+ Genre Assets in Catalog:       ${a2plusAfter.length}\n`);

  if (protectedLucaAfter.length !== protectedLucaBefore.length) {
    console.error('FAIL-CLOSED: Protected Luca asset count changed! Aborting write.');
    process.exit(1);
  }

  if (dryRun) {
    console.log('Dry-run complete. No files were modified.');
    process.exit(0);
  }

  // Write files
  for (const dir of [publicDir, mediaDir, bundledDir]) {
    fs.mkdirSync(dir, { recursive: true });
  }

  let copied = 0;
  for (const asset of toAdd) {
    const destName = path.basename(asset.audioUrl);
    const srcFile = path.join(audioSrcDir, destName);
    fs.copyFileSync(srcFile, path.join(publicDir, destName));
    fs.copyFileSync(srcFile, path.join(mediaDir, destName));
    fs.copyFileSync(srcFile, path.join(bundledDir, destName));
    copied++;
  }

  fs.writeFileSync(catalogPath, JSON.stringify({ assets: merged }, null, 2) + '\n', 'utf8');
  writeBundledAssets(merged);

  console.log('================================================================');
  console.log('  PACKAGING COMPLETED');
  console.log('================================================================');
  console.log(`  Updated catalog:         ${catalogPath}`);
  console.log(`  Copied MP3 assets:       ${copied} files to public/media/bundled`);
  console.log(`  Generated manifest:      mobile/src/audio/bundledAssets.ts`);
  console.log(`  Protected Luca Assets:   100% PRESERVED (${protectedLucaAfter.length})`);
  console.log('================================================================\n');

  console.log('Next step: node mobile/scripts/validate-a2plus-audio.js');
}

main();
