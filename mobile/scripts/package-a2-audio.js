/**
 * MERGE A2 sentence audio (chapters 21–40) into the existing catalog.
 *
 * NEVER replaces catalog.json. NEVER deletes Ch1–20 assets.
 * Do not run package-a1-audio.js for A2.
 *
 * Usage:
 *   node mobile/scripts/package-a2-audio.js --dry-run
 *   node mobile/scripts/package-a2-audio.js
 *
 * Writes (only without --dry-run):
 *   mobile/content/audio/catalog.json          ← merge
 *   mobile/public/audio/a1/*.mp3               ← same packaged path as A1 (runtime-safe)
 *   mobile/content/audio/bundled/*.mp3
 *   mobile/src/audio/media/*.mp3
 *   mobile/src/audio/bundledAssets.ts          ← A1 + A2 requires
 */
const fs = require('fs');
const path = require('path');
const {
  MIN_CHAPTER,
  MAX_CHAPTER,
  mobileRoot,
  repoRoot,
  contentRoot,
  parseA2Range,
  isA1ContentId,
  isA2ContentId,
  chapterNumberFromContentId,
  collectClipPlan,
  loadJson,
} = require('./a2-audio-common');

const registryPath = path.join(repoRoot, 'services', 'tts-gateway', 'data', 'registry.json');
const audioSrcDir = path.join(repoRoot, 'services', 'tts-gateway', 'data', 'audio');
const publicDir = path.join(mobileRoot, 'public', 'audio', 'a1');
const mediaDir = path.join(mobileRoot, 'src', 'audio', 'media');
const bundledDir = path.join(contentRoot, 'audio', 'bundled');
const catalogPath = path.join(contentRoot, 'audio', 'catalog.json');

function writeBundledAssets(assets) {
  const manifestPath = path.join(mobileRoot, 'src', 'audio', 'bundledAssets.ts');
  const byFile = new Map();
  for (const asset of assets) {
    const file = path.basename(asset.audioUrl || '');
    if (!file) continue;
    const key = file.replace(/\.mp3$/i, '');
    if (!byFile.has(key)) byFile.set(key, file);
  }
  const lines = [...byFile.entries()].map(
    ([key, file]) => `  '${key}': require('./media/${file}'),`,
  );
  const manifest = `/* Auto-generated by scripts/package-a2-audio.js (merge A1+A2) — do not edit. */
/* eslint-disable @typescript-eslint/no-require-imports */
export const bundledAudioModules: Record<string, number> = {
${lines.join('\n')}
};

export function bundledModuleForUrl(audioUrl: string): number | null {
  const file = audioUrl
    .replace(/^\\/audio\\/a1\\//, '')
    .replace(/^\\/audio\\/a2\\//, '')
    .replace(/^\\.\\/bundled\\//, '')
    .replace(/^bundled:/, '');
  const key = file.replace(/\\.mp3$/i, '');
  return bundledAudioModules[key] ?? null;
}
`;
  fs.writeFileSync(manifestPath, manifest, 'utf8');
}

function main() {
  const { dryRun, from, to } = parseA2Range(['--from=21', '--to=40', ...process.argv.slice(2)]);
  console.log('A2 AUDIO PACKAGE — MERGE ONLY');
  console.log(`Range filter: chapters ${from}–${to}`);
  console.log('Ch1–20 catalog entries will be preserved.\n');

  const authoredIds = new Set(collectClipPlan(from, to).clips.map((c) => c.contentId));

  if (!fs.existsSync(catalogPath)) {
    console.error('Missing catalog:', catalogPath);
    process.exit(1);
  }
  const existingCatalog = loadJson(catalogPath);
  const existingAssets = existingCatalog.assets ?? [];
  const a1Before = existingAssets.filter((a) => isA1ContentId(a.contentId));
  const a1ContentIds = new Set(a1Before.map((a) => a.contentId));
  const a1CacheKeys = new Set(a1Before.map((a) => a.cacheKey || a.id).filter(Boolean));
  const a1Files = new Set(a1Before.map((a) => path.basename(a.audioUrl || '')));

  if (!fs.existsSync(registryPath)) {
    console.log(`No TTS registry at ${registryPath}`);
    console.log(`Existing A1 entries: ${a1Before.length}`);
    console.log('Nothing to merge.');
    if (dryRun) {
      console.log('Dry-run: catalog.json was not modified.');
      process.exit(0);
    }
    process.exit(1);
  }

  const registry = loadJson(registryPath);
  const incoming = (registry.assets ?? []).filter((a) => {
    if (!(a.status === 'approved' || a.status === 'review_required')) return false;
    if (a.speed !== 'normal') return false;
    if (!authoredIds.has(a.contentId)) return false;
    const n = chapterNumberFromContentId(a.contentId);
    return n != null && n >= from && n <= to;
  });

  const collisions = [];
  const toAdd = [];
  const missingSource = [];
  const providerRank = { google: 3, elevenlabs: 2, azure: 1 };
  const bestByContent = new Map();
  for (const asset of incoming) {
    const prev = bestByContent.get(asset.contentId);
    if (!prev) {
      bestByContent.set(asset.contentId, asset);
      continue;
    }
    const prevRank = providerRank[prev.provider] ?? 0;
    const nextRank = providerRank[asset.provider] ?? 0;
    if (nextRank > prevRank) bestByContent.set(asset.contentId, asset);
  }

  for (const asset of bestByContent.values()) {
    const n = chapterNumberFromContentId(asset.contentId);
    if (n == null || n < MIN_CHAPTER || n > MAX_CHAPTER) {
      collisions.push(`Unexpected chapter for ${asset.contentId}`);
      continue;
    }
    if (a1ContentIds.has(asset.contentId)) {
      collisions.push(`contentId collides with A1: ${asset.contentId}`);
      continue;
    }
    // Shared cacheKey / filename with A1 is intentional text+voice reuse.
    const key = asset.cacheKey || asset.id;
    const destName = `${key}.mp3`;
    const srcFile = path.join(audioSrcDir, destName);
    if (!fs.existsSync(srcFile)) {
      missingSource.push(asset.contentId);
      continue;
    }
    toAdd.push({
      ...asset,
      status: 'approved',
      audioUrl: `/audio/a1/${destName}`,
    });
  }

  if (collisions.length) {
    console.error('A2 packaging aborted — collisions with frozen A1 audio:');
    for (const line of collisions.slice(0, 20)) console.error(`  - ${line}`);
    process.exit(1);
  }

  const mergedById = new Map();
  for (const asset of existingAssets) mergedById.set(asset.contentId, asset);
  for (const asset of toAdd) mergedById.set(asset.contentId, asset);
  const merged = [...mergedById.values()];
  const a1After = merged.filter((a) => isA1ContentId(a.contentId));

  console.log(`A1 before: ${a1Before.length}`);
  console.log(`A2 candidates in registry: ${incoming.length}`);
  console.log(`A2 to merge: ${toAdd.length}`);
  console.log(`Missing source MP3s: ${missingSource.length}`);
  console.log(`A1 after (projected): ${a1After.length}`);
  console.log(`Lost A1: ${a1Before.length - a1After.length}`);

  if (a1After.length !== a1Before.length) {
    console.error('A1 preservation check failed — aborting write.');
    process.exit(1);
  }

  if (dryRun) {
    console.log('\nDry-run: no files written. catalog.json / bundledAssets.ts unchanged.');
    process.exit(0);
  }

  for (const dir of [publicDir, mediaDir, bundledDir]) fs.mkdirSync(dir, { recursive: true });
  for (const asset of toAdd) {
    const destName = path.basename(asset.audioUrl);
    const srcFile = path.join(audioSrcDir, destName);
    fs.copyFileSync(srcFile, path.join(publicDir, destName));
    fs.copyFileSync(srcFile, path.join(mediaDir, destName));
    fs.copyFileSync(srcFile, path.join(bundledDir, destName));
  }

  fs.writeFileSync(catalogPath, JSON.stringify({ assets: merged }, null, 2) + '\n', 'utf8');
  writeBundledAssets(merged);

  console.log(`\nMerged ${toAdd.length} A2 assets into ${catalogPath}`);
  console.log(`Catalog total: ${merged.length} (A1 ${a1After.length} preserved)`);
}

main();
